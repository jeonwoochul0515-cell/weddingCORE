/** 재결례 글에서 함께 보여주는 개별 사건 */
export type RulingCase = {
  name: string;
  decidedOn: string;
  /** 인용은 처분이 취소된 것, 기각은 유지된 것 */
  result: '인용' | '기각' | '각하';
  gist: string;
};

export type Interpretation = {
  /**
   * 글의 종류.
   * interpretation — 법제처 법령해석. "법을 어떻게 읽나"
   * ruling — 행정심판 재결례. "그 처분이 정당했나"
   * court — 법원 판례. "형사처벌 대상인가"
   */
  kind: 'interpretation' | 'ruling' | 'court';
  /** URL 경로. 바꾸면 색인된 주소가 깨지니 고정한다 */
  slug: string;
  /** 실무자가 검색할 만한 말로 지은 제목 */
  title: string;
  /** 목록과 검색 결과에 쓰는 한 줄 요약 */
  summary: string;
  /** 실무자가 실제로 하는 형태의 질문 */
  question: string;
  /** 두괄식 결론. 먼저 답하고 뒤에서 풀어 쓴다 */
  answer: string;
  /** 왜 그렇게 보았는지 */
  reasoning: string[];
  /** 현장에서 무엇이 달라지는지 */
  practice: string[];
  /** 관련 조문 */
  articles: string[];
  /** 질의기관 */
  agency: string;
  /** 회신일자 */
  answeredOn: string;
  /** 법제처 법령해석례 일련번호 */
  sourceId: string;
  /** 법제처가 붙인 원래 안건명. 재결례 글에서는 자료 출처를 적는다 */
  sourceTitle: string;
  /** 재결례 글에서 근거로 삼은 사건들 */
  cases?: RulingCase[];
};

